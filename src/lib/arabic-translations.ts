/**
 * Translates any English, French or non-Moroccan terminology text to Modern Standard Arabic.
 */
export function translateToArabic(text: string): string {
  if (!text || typeof text !== "string") return text;

  const trimmed = text.trim();
  if (!trimmed) return text;

  // 1. Direct dictionary match
  if (ARABIC_DICTIONARY[trimmed]) {
    return ARABIC_DICTIONARY[trimmed];
  }

  // 2. Case-insensitive dictionary match
  const lower = trimmed.toLowerCase();
  for (const [key, val] of Object.entries(ARABIC_DICTIONARY)) {
    if (key.toLowerCase() === lower) {
      return val;
    }
  }

  // 3. Dynamic regex pattern match
  for (const item of DYNAMIC_PATTERNS) {
    if (item.pattern.test(trimmed)) {
      return trimmed.replace(item.pattern, item.replacer);
    }
  }

  // 4. Moroccan terminology cleanup if old terms are present
  if (
    trimmed.includes("الدورات") ||
    trimmed.includes("الطلاب") ||
    trimmed.includes("الفصول") ||
    trimmed.includes("طالبs")
  ) {
    return trimmed
      .replace(/الدورات/g, "الدروس")
      .replace(/دورة/g, "درس")
      .replace(/دورات/g, "دروس")
      .replace(/الطلاب/g, "التلاميذ")
      .replace(/طالبs/g, "تلاميذ")
      .replace(/طالب/g, "تلميذ")
      .replace(/طلاب/g, "تلاميذ")
      .replace(/الفصول/g, "الأقسام")
      .replace(/فصول/g, "أقسام");
  }

  return text;
}
