/**
 * Translates English text to French.
 */
export function translateToFrench(text: string): string {
  if (!text || typeof text !== "string") return text;

  const trimmed = text.trim();
  if (!trimmed) return text;

  // 1. Direct dictionary match
  if (FRENCH_DICTIONARY[trimmed]) {
    return FRENCH_DICTIONARY[trimmed];
  }

  // 2. Case-insensitive dictionary match
  const lower = trimmed.toLowerCase();
  for (const [key, val] of Object.entries(FRENCH_DICTIONARY)) {
    if (key.toLowerCase() === lower) {
      return val;
    }
  }

  // 3. Dynamic regex patterns
  for (const { pattern, replacer } of DYNAMIC_PATTERNS_FR) {
    if (pattern.test(trimmed)) {
      return trimmed.replace(pattern, replacer);
    }
  }

  return text;
}
