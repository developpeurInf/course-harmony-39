-- L'aperçu du dernier message indique une pièce jointe quand il n'y a pas de texte
create or replace function public.support_preview(p_body text, p_att jsonb, p_loc jsonb)
returns text language sql immutable set search_path = '' as $$
  select case
    when char_length(coalesce(p_body, '')) > 0 then left(p_body, 160)
    when p_loc is not null then '📍 Position'
    when jsonb_array_length(coalesce(p_att, '[]'::jsonb)) > 0 then '📎 ' || coalesce(p_att->0->>'name', 'Pièce jointe')
    else '' end;
$$;
