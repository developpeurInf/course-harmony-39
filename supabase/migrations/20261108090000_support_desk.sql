alter table public.support_messages add column if not exists internal boolean not null default false;

-- Reprise des tickets existants
update public.support_tickets t set
  last_message_at = m.created_at,
  last_message_preview = left(m.body, 160),
  last_from_staff = m.is_staff
from (
  select distinct on (ticket_id) ticket_id, created_at, body, is_staff
  from public.support_messages where not internal
  order by ticket_id, created_at desc
) m
where m.ticket_id = t.id and t.last_message_at is null;
update public.support_tickets set closed_at = updated_at where status = 'closed' and closed_at is null;

