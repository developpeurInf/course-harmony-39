-- ---------------------------------------------------------------------
-- Ticket : ce que le professeur peut changer (fermer, rouvrir, lu, avis)
-- ---------------------------------------------------------------------
create or replace function public.support_ticket_guard()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  -- Mises à jour faites par le déclencheur des messages
  if pg_trigger_depth() > 1 then return new; end if;

  if not public.has_admin_permission('admin.support.manage') then
    new.number := old.number;
    new.author_id := old.author_id;
    new.priority := old.priority;
    new.assigned_to := old.assigned_to;
    new.staff_read_at := old.staff_read_at;
    new.last_message_at := old.last_message_at;
    new.last_message_preview := old.last_message_preview;
    new.last_from_staff := old.last_from_staff;
    new.created_at := old.created_at;
    if new.status is distinct from old.status and new.status not in ('open', 'closed') then
      new.status := old.status;
    end if;
    if new.rating is distinct from old.rating and new.status <> 'closed' then
      new.rating := old.rating;
      new.rating_comment := old.rating_comment;
    end if;
  end if;

  if new.status = 'closed' and old.status <> 'closed' then
    new.closed_at := now();
  elsif new.status <> 'closed' then
    new.closed_at := null;
  end if;
  return new;
end;
$$;
drop trigger if exists support_ticket_guard on public.support_tickets;
create trigger support_ticket_guard before update on public.support_tickets
  for each row execute function public.support_ticket_guard();

-- ---------------------------------------------------------------------
-- Après un message : statut, aperçu, lu, assignation, notifications
-- ---------------------------------------------------------------------
create or replace function public.support_message_after()
returns trigger language plpgsql security definer set search_path = '' as $$
declare t public.support_tickets; v_staff boolean;
begin
  select * into t from public.support_tickets where id = new.ticket_id;
  v_staff := new.author_id <> t.author_id and public.has_admin_permission('admin.support.manage', new.author_id);
  if v_staff and not new.is_staff then
    update public.support_messages set is_staff = true where id = new.id;
  end if;

  -- Note interne : rien ne change pour le professeur
  if new.internal then
    update public.support_tickets set staff_read_at = now() where id = t.id;
    return new;
  end if;

  update public.support_tickets set
    updated_at = now(),
    last_message_at = now(),
    last_message_preview = public.support_preview(new.body, new.attachments, new.location),
    last_from_staff = v_staff,
    status = case
      when v_staff then 'answered'
      when t.status in ('answered', 'closed') then 'open'
      else t.status end,
    closed_at = case when v_staff or t.status <> 'closed' then t.closed_at else null end,
    assigned_to = case when v_staff then coalesce(t.assigned_to, new.author_id) else t.assigned_to end,
    staff_read_at = case when v_staff then now() else t.staff_read_at end,
    author_read_at = case when v_staff then t.author_read_at else now() end
  where id = t.id;

  if v_staff then
    insert into public.notifications (user_id, title, message, type)
    values (t.author_id, 'Réponse du support', '#' || t.number || ' · ' || t.subject, 'info');
  elsif t.assigned_to is not null and t.assigned_to <> new.author_id then
    insert into public.notifications (user_id, title, message, type)
    values (t.assigned_to, 'Nouveau message de support', '#' || t.number || ' · ' || t.subject, 'info');
  end if;
  return new;
end;
$$;

-- ---------------------------------------------------------------------
-- Créer un ticket et son premier message en une fois
-- ---------------------------------------------------------------------
create or replace function public.support_create_ticket(p_subject text, p_category text, p_body text, p_priority text default 'normal')
returns public.support_tickets language plpgsql security definer set search_path = '' as $$
declare t public.support_tickets;
begin
  if auth.uid() is null then raise exception 'Connexion requise' using errcode = '42501'; end if;
  if char_length(coalesce(trim(p_body), '')) = 0 then raise exception 'Message vide'; end if;
  if (select count(*) from public.support_tickets where author_id = auth.uid() and created_at > now() - interval '1 day') >= 10 then
    raise exception 'Trop de demandes aujourd''hui, réessayez demain.';
  end if;
  insert into public.support_tickets (author_id, subject, category, priority)
  values (auth.uid(), trim(p_subject), coalesce(p_category, 'question'),
          case when p_priority in ('low', 'normal', 'high', 'urgent') then p_priority else 'normal' end)
  returning * into t;
  insert into public.support_messages (ticket_id, author_id, body) values (t.id, auth.uid(), trim(p_body));
  select * into t from public.support_tickets where id = t.id;
  return t;
end;
$$;
revoke execute on function public.support_create_ticket(text, text, text, text) from anon;
grant execute on function public.support_create_ticket(text, text, text, text) to authenticated;

-- Marquer un ticket comme lu (par l'équipe ou par son auteur)
create or replace function public.support_mark_read(p_ticket uuid)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if public.has_admin_permission('admin.support.manage') then
    update public.support_tickets set staff_read_at = now() where id = p_ticket;
  else
    update public.support_tickets set author_read_at = now() where id = p_ticket and author_id = auth.uid();
  end if;
end;
$$;
revoke execute on function public.support_mark_read(uuid) from anon;
grant execute on function public.support_mark_read(uuid) to authenticated;

-- Liste admin : tickets + nom / e-mail du professeur + nombre de messages
create or replace function public.support_admin_tickets()
returns table (
  id uuid, number bigint, author_id uuid, subject text, category text, status text, priority text,
  assigned_to uuid, created_at timestamptz, updated_at timestamptz, last_message_at timestamptz,
  last_message_preview text, last_from_staff boolean, staff_read_at timestamptz, author_read_at timestamptz,
  closed_at timestamptz, rating smallint, rating_comment text,
  author_name text, author_email text, messages int, author_tickets int
)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.has_admin_permission('admin.support.manage') then
    raise exception 'Accès réservé à l''administration' using errcode = '42501';
  end if;
  return query
  select t.id, t.number, t.author_id, t.subject, t.category, t.status, t.priority,
         t.assigned_to, t.created_at, t.updated_at, t.last_message_at,
         t.last_message_preview, t.last_from_staff, t.staff_read_at, t.author_read_at,
         t.closed_at, t.rating, t.rating_comment,
         coalesce(p.name, u.email)::text, u.email::text,
         (select count(*)::int from public.support_messages m where m.ticket_id = t.id and not m.internal),
         (select count(*)::int from public.support_tickets t2 where t2.author_id = t.author_id)
  from public.support_tickets t
  left join auth.users u on u.id = t.author_id
  left join public.profiles p on p.id = t.author_id
  order by coalesce(t.last_message_at, t.updated_at) desc
  limit 2000;
end;
$$;
revoke execute on function public.support_admin_tickets() from anon;
grant execute on function public.support_admin_tickets() to authenticated;

-- Compteur pour le menu : tickets à traiter non lus
create or replace function public.support_unread_count()
returns int language sql stable security definer set search_path = '' as $$
  select case when public.has_admin_permission('admin.support.manage') then (
    select count(*)::int from public.support_tickets
    where status in ('open', 'in_progress') and not last_from_staff
      and coalesce(last_message_at, created_at) > coalesce(staff_read_at, '-infinity'::timestamptz)
  ) else (
    select count(*)::int from public.support_tickets
    where author_id = auth.uid() and last_from_staff
      and last_message_at > coalesce(author_read_at, '-infinity'::timestamptz)
  ) end;
$$;
revoke execute on function public.support_unread_count() from anon;
grant execute on function public.support_unread_count() to authenticated;

