-- Chemin : <id du ticket>/<fichier>. Accès : auteur du ticket ou équipe support.
create or replace function public.support_can_access_ticket(p_ticket text)
returns boolean language sql stable security definer set search_path = '' as $$
  select public.has_admin_permission('admin.support.manage')
    or exists (select 1 from public.support_tickets t where t.id::text = p_ticket and t.author_id = auth.uid());
$$;
revoke execute on function public.support_can_access_ticket(text) from anon;
grant execute on function public.support_can_access_ticket(text) to authenticated;

